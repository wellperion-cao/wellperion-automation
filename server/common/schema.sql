-- actor_code CHECK 는 A-1~A-12 형식만 받게 하되 NULL 은 허용한다 — 과거 1,976건에 코드 없는 행이 있다.
-- 코드 필수(fail-closed)로 조이는 것은 정합 확인 뒤 2단계.
CREATE TABLE IF NOT EXISTS hr.automation_log (
  log_id      BIGSERIAL PRIMARY KEY,
  tenant_id   TEXT NOT NULL DEFAULT 'wellperion',
  occurred_at TIMESTAMPTZ NOT NULL,
  actor       TEXT NOT NULL,
  actor_code  TEXT CHECK (actor_code IS NULL OR actor_code ~ '^A-(1[0-2]|[1-9])$'),
  work        TEXT,                                     -- [PII] 지원자 실명 병기가 의무라 이름이 들어온다
  result      TEXT,
  target_ref  TEXT,                                     -- 'appl:112' 처럼 (탭:행) — legacy_row_map 으로 새 PK 를 찾는다
  legacy_tab  TEXT,
  legacy_row  INTEGER,
  is_test     BOOLEAN NOT NULL DEFAULT FALSE,
  data        JSONB,
  synced_at   TIMESTAMPTZ,
  UNIQUE (tenant_id, legacy_tab, legacy_row)
);
CREATE INDEX IF NOT EXISTS ix_hr_autolog_at    ON hr.automation_log (tenant_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_hr_autolog_actor ON hr.automation_log (tenant_id, actor_code, occurred_at DESC);

-- ── 18. 명령큐 ──────────────────────────────────────────────────────────────────────────────────
-- ⚠️ 현행 회수(cmd-pull)가 상태를 delivered 로 바꾸는 쓰기성 부작용이 있어 적재 전 조회를 안 했다 —
--    건수 미확인 상태다(진단 §6 미확인 10). 표만 준비하고 적재는 매니저 확인 뒤.
CREATE TABLE IF NOT EXISTS hr.command_queue (
  command_id   BIGSERIAL PRIMARY KEY,
  tenant_id    TEXT NOT NULL DEFAULT 'wellperion',
  status       TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'delivered', 'done', 'canceled')),
  command      TEXT,
  payload      JSONB,
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  delivered_at TIMESTAMPTZ,
  done_at      TIMESTAMPTZ,
  legacy_tab   TEXT,
  legacy_row   INTEGER,
  is_test      BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE (tenant_id, legacy_tab, legacy_row)
);
CREATE INDEX IF NOT EXISTS ix_hr_cmdq_status ON hr.command_queue (tenant_id, status, created_at);

-- ── 19. rNN 역인덱스 ────────────────────────────────────────────────────────────────────────────
-- (시트 탭, 행번호) → (새 표, 새 PK). 사진 파일명 r<row>.jpg · 자동화로그 1,976건 · 과거 STATE 기록 ·
-- 사람의 "r112" 호칭을 새 시스템에서 되짚기 위한 단방향 조회표. 이관 시 각 표 적재와 같은 트랜잭션에서 채운다.
CREATE TABLE IF NOT EXISTS hr.legacy_row_map (
  tenant_id    TEXT NOT NULL DEFAULT 'wellperion',
  legacy_tab   TEXT NOT NULL,
  legacy_row   INTEGER NOT NULL,
  target_table TEXT NOT NULL,
  target_id    BIGINT NOT NULL,
  mapped_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, legacy_tab, legacy_row)
);
CREATE INDEX IF NOT EXISTS ix_hr_legacy_target ON hr.legacy_row_map (tenant_id, target_table, target_id);

-- ── 20-21. 이관 진행 기록 ───────────────────────────────────────────────────────────────────────
-- migrate_hr.py 가 어디까지 갔는지 남기는 자리. '부분 적재 상태로 조용히 끝남'을 막는 장치다 —
-- 끝나지 않은 실행은 status='running' 으로 남고, 실패는 'failed' 로 남는다. 성공만 'ok'.
-- 'aborted' = 강제 종료 등으로 running 인 채 남은 run 을 다음 apply 실행이 닫은 것(aborted_by_run 에 닫은 run 의 id).
-- apply 는 세션 advisory lock(HR_RUN_LOCK_KEY = 11050002 · common/db.py 의 DDL 락 11050001 과 다른 값)으로 단일 실행.
-- 읽기 API 봉투의 as_of = 마지막 mode='apply' AND status='ok' run 의 finished_at (aws2 §0.3).
CREATE TABLE IF NOT EXISTS hr.migration_run (
  run_id      BIGSERIAL PRIMARY KEY,
  tenant_id   TEXT NOT NULL DEFAULT 'wellperion',
  mode        TEXT NOT NULL,                            -- 'dry-run' · 'apply'
  started_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ,
  status      TEXT NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'ok', 'failed', 'aborted')),
  note        TEXT,
  host        TEXT,
  batch_at    TIMESTAMPTZ,                              -- 그 실행의 배치 기준 시각(첫 fetch 전에 1회 채취) — 소실 판정·synced_at 의 기준
  warnings    INTEGER NOT NULL DEFAULT 0,               -- 경고(건너뜀·잉여·소실·신원변경·고아) 누계 — failed 가 아니다
  aborted_by_run BIGINT                                 -- running 으로 남아 있던 이 run 을 닫은 새 run 의 id
);
ALTER TABLE hr.migration_run ADD COLUMN IF NOT EXISTS batch_at       TIMESTAMPTZ;
ALTER TABLE hr.migration_run ADD COLUMN IF NOT EXISTS warnings       INTEGER NOT NULL DEFAULT 0;
ALTER TABLE hr.migration_run ADD COLUMN IF NOT EXISTS aborted_by_run BIGINT;
CREATE TABLE IF NOT EXISTS hr.migration_step (
  step_id    BIGSERIAL PRIMARY KEY,
  run_id     BIGINT NOT NULL REFERENCES hr.migration_run(run_id) ON DELETE CASCADE,
  tenant_id  TEXT NOT NULL DEFAULT 'wellperion',
  tab        TEXT NOT NULL,                             -- 원천 탭·db 열쇠
  phase      TEXT NOT NULL,                             -- fetch · load · verify
  source_rows   INTEGER NOT NULL DEFAULT 0,
  loaded_rows   INTEGER NOT NULL DEFAULT 0,
  skipped_test  INTEGER NOT NULL DEFAULT 0,
  failed_rows   INTEGER NOT NULL DEFAULT 0,
  matched_rows  INTEGER NOT NULL DEFAULT 0,             -- 전수 대조에서 값까지 같았던 행
  recall_pct    NUMERIC(5,2),                           -- 재현율 = matched / source (함정노트 #48 목표선 99.5％)
  ok         BOOLEAN NOT NULL DEFAULT FALSE,
  detail     JSONB,                                     -- ⛔ 개인정보 원문 금지 — 칸 이름·행번호·건수만
  at         TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_hr_migstep_run ON hr.migration_step (run_id, at);

-- ── 22. 조회 기록(열람 원장) ────────────────────────────────────────────────────────────────────
-- 인사·문의·회원·업무 어느 도메인에도 '열람' 기록이 없다 — 남는 것은 쓰기 원장뿐이고, 관문 접근 로그도
-- 저장소 설정에 지시자가 없다. 시범 전환 시점부터는 원문이 서버에서 나가므로 그 전에 기록 자리가 있어야 한다.
-- 관문이 로그인 이메일을 상류로 넘기고 있어(erp_api/api.nginx.conf) '누가'는 이미 확보돼 있다.
-- ⛔ 행 내용·개인정보 값은 담지 않는다. 남기는 것은 '누가·언제·어느 열쇠를·마스킹 여부'까지다.
--    (params 에도 상한·시작위치·기간·테스트 포함 여부 같은 요청 파라미터만 넣는다 — 조회 결과는 넣지 않는다.)
-- ⚠️ 배포 준비물: 서버 DB 계정에 이 표의 INSERT 권한이 필요하다. 읽기 라우트는 읽기 전용 세션으로 열기 때문에
--    같은 연결로는 못 쓰고, 기록 전용 쓰기 연결을 짧게 열고 닫는다(api_hr.py).
-- ⚠️ 보존기간은 미정이다 — 파기·보유기간 정책이 법적 검토 지점이라 표만 만들고 삭제 배치는 넣지 않는다.
--    나중에 기존 정리 스크립트(prune_track.py 계열)와 같은 방식으로 붙일 수 있게 시각 인덱스만 미리 둔다.
CREATE TABLE IF NOT EXISTS hr.access_log (
  access_id       BIGSERIAL PRIMARY KEY,
  tenant_id       TEXT NOT NULL DEFAULT 'wellperion',
  occurred_at     TIMESTAMPTZ NOT NULL DEFAULT now(),      -- 시간대 포함 — 서버가 UTC 여도 뒤에 맞춰 읽을 수 있다
  user_email      TEXT,                                    -- [PII] 관문이 넘긴 로그인 이메일(화면이 보낸 이름이 아니다)
  role            TEXT,                                    -- 판정 역할 admin · viewer (헤더 원문이 아니라 판정 결과)
  db_key          TEXT,                                    -- 조회 열쇠 emp·appl·leave·autolog…
  route           TEXT,                                    -- 'GET /api/hr/{db}' · 'POST /api/hr/read'
  response_status TEXT,                                    -- ok · scope-blocked · unknown-db · bad-date · db-error …
  row_count       INTEGER,                                 -- 반환 행수(내용은 담지 않는다)
  masked          BOOLEAN,                                 -- ★봉투의 masked 와 같은 값 — 사후 '누가 원문을 봤나' 대조의 근거
  params          JSONB,                                   -- 상한·시작위치·기간·테스트 포함 여부만
  deny_reason     TEXT,
  client_ip       TEXT
);
CREATE INDEX IF NOT EXISTS ix_hr_acclog_at   ON hr.access_log (tenant_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_hr_acclog_user ON hr.access_log (tenant_id, user_email, occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_hr_acclog_key  ON hr.access_log (tenant_id, db_key, occurred_at DESC);

