  PRIMARY KEY (tenant_id, reg_id)
);
CREATE TABLE IF NOT EXISTS lost_found (
  tenant_id  TEXT NOT NULL DEFAULT 'wellperion',
  found_id   TEXT NOT NULL,
  status     TEXT,
  created_at TEXT,
  data       TEXT NOT NULL,
