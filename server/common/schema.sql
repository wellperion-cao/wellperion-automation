CREATE TABLE IF NOT EXISTS hold_items (
  tenant_id  TEXT NOT NULL DEFAULT 'wellperion',
  intake_row TEXT NOT NULL,
  status     TEXT,
  done       BOOLEAN NOT NULL DEFAULT FALSE,   -- 접수 GAS hold_done_keys(처리메모 '휴회완료') 조인 결과
  applied_at TEXT,
  data       TEXT NOT NULL,
  synced_at  TEXT NOT NULL,
