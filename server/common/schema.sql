-- 점검 미러 (배 922 레인 S · 2026-09-03) — sync_check.py 가 점검 GAS 응답을 부서·종류·열쇠로 그대로 싣는다.
-- kind = board(시설 날짜) · ledger(날짜|성별) · today_live(날짜) · monthly(월) · weekly('-'). 화면은 GAS 응답 모양 그대로 읽는다.
